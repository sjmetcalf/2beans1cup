def ring_module():
    """Emit a JS module with the ring + lettering markup (no illustration), using currentColor."""
    inner = f'''<circle cx="{C}" cy="{C}" r="{OUTER_R}" fill="none" stroke="currentColor" stroke-width="{OUTER_W}"/>
<circle cx="{C}" cy="{C}" r="{INNER_R}" fill="none" stroke="currentColor" stroke-width="{INNER_W}"/>
<g fill="currentColor">
{arc_text("TWO BEANS", TOP_BASELINE, TEXT_SIZE, 0.16, "top")}
{arc_text("ONE CUP", BOTTOM_BASELINE, TEXT_SIZE, 0.16, "bottom")}
<circle cx="{C-BAND_MID:.2f}" cy="{C}" r="7"/><circle cx="{C+BAND_MID:.2f}" cy="{C}" r="7"/>
</g>'''
    return "// Generated by logo/build_badge.py — badge ring with lettering outlined from Inter Display SemiBold.\nexport const RING = " + __import__("json").dumps(inner) + ";\n"
