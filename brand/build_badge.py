"""Build the 2beans1cup badge as a self-contained SVG (text converted to outlines)."""
import base64, math, sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

FONT = "/usr/share/fonts/opentype/inter/InterDisplay-SemiBold.otf"
font = TTFont(FONT)
gs = font.getGlyphSet()
cmap = font.getBestCmap()
upm = font["head"].unitsPerEm
hmtx = font["hmtx"]

C = 500  # center

# Ring geometry. Lettering is centred optically in the band between the two rings.
OUTER_R, OUTER_W = 482, 7
INNER_R, INNER_W = 362, 2.5
TEXT_SIZE = 70
CAP = font["OS/2"].sCapHeight / upm * TEXT_SIZE
BAND_MID = ((OUTER_R - OUTER_W / 2) + (INNER_R + INNER_W / 2)) / 2
TOP_BASELINE = BAND_MID - CAP / 2      # top text: caps point outward
BOTTOM_BASELINE = BAND_MID + CAP / 2   # bottom text: caps point inward


def glyph_path(ch, size):
    """Return (svg path d, advance) for a glyph scaled to `size`, baseline at y=0, x from 0."""
    name = cmap[ord(ch)]
    s = size / upm
    pen = SVGPathPen(gs)
    gs[name].draw(TransformPen(pen, (s, 0, 0, -s, 0, 0)))
    return pen.getCommands(), hmtx[name][0] * s


def arc_text(text, r, size, tracking, where):
    items = [glyph_path(ch, size) for ch in text]
    track = tracking * size
    widths = [adv for _, adv in items]
    L = sum(widths) + track * (len(items) - 1)
    out, s = [], 0.0
    for (d, adv), ch in zip(items, text):
        mid = s + adv / 2
        off = (mid - L / 2) / r
        if where == "top":
            th = -math.pi / 2 + off
            rot = math.degrees(th) + 90
        else:
            th = math.pi / 2 - off
            rot = math.degrees(th) - 90
        x, y = C + r * math.cos(th), C + r * math.sin(th)
        if d:
            out.append(
                f'<path d="{d}" transform="translate({x:.2f} {y:.2f}) rotate({rot:.3f}) translate({-adv/2:.2f} 0)"/>'
            )
        s += adv + track
    return "\n    ".join(out)


def badge(ink, bg, art_png):
    art = base64.b64encode(open(art_png, "rb").read()).decode()
    # illustration aspect from file
    from PIL import Image
    w, h = Image.open(art_png).size
    aw = 590
    ah = aw * h / w
    bg_el = f'<circle cx="{C}" cy="{C}" r="496" fill="{bg}"/>' if bg else ""
    return f'''<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="0 0 1000 1000" role="img" aria-label="Two Beans, One Cup">
  {bg_el}
  <g fill="none" stroke="{ink}">
    <circle cx="{C}" cy="{C}" r="{OUTER_R}" stroke-width="{OUTER_W}"/>
    <circle cx="{C}" cy="{C}" r="{INNER_R}" stroke-width="{INNER_W}"/>
  </g>
  <g fill="{ink}">
    {arc_text("TWO BEANS", TOP_BASELINE, TEXT_SIZE, 0.16, "top")}
    {arc_text("ONE CUP", BOTTOM_BASELINE, TEXT_SIZE, 0.16, "bottom")}
    <circle cx="{C-BAND_MID:.2f}" cy="{C}" r="7"/>
    <circle cx="{C+BAND_MID:.2f}" cy="{C}" r="7"/>
  </g>
  <image x="{C-aw/2:.1f}" y="{C-ah/2+6:.1f}" width="{aw}" height="{ah:.1f}" href="data:image/png;base64,{art}"/>
</svg>
'''


if __name__ == "__main__":
    open("badge-roast.svg", "w").write(badge("#2b1d14", None, "beans-roast.png"))
    open("badge-cream.svg", "w").write(badge("#f4ede3", None, "beans-cream.png"))
    open("badge-roast-on-cream.svg", "w").write(badge("#2b1d14", "#f4ede3", "beans-roast.png"))
